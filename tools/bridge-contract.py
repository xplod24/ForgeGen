#!/usr/bin/env python3
"""Generate the Android wire DTOs and route catalog from the supplied Bridge OpenAPI."""
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
spec = json.loads((root / "docs/bridge/openapi.json").read_text())
schemas = spec["components"]["schemas"]


def name(value):
    if value.startswith("Page_"):
        return "Bridge" + value.removeprefix("Page_").rstrip("_") + "Page"
    return "Bridge" + value


def kind(schema):
    if "$ref" in schema:
        return name(schema["$ref"].split("/")[-1])
    if "anyOf" in schema:
        return kind(next(s for s in schema["anyOf"] if s.get("type") != "null"))
    t = schema.get("type")
    if t == "array":
        return "List<" + kind(schema["items"]) + ">"
    if t == "object":
        v = schema.get("additionalProperties")
        return "Map<String, " + kind(v) + ">" if isinstance(v, dict) else "JsonElement"
    return {"boolean": "Boolean", "integer": "Long", "number": "Double", "string": "String"}.get(t, "JsonElement")


lines = ["// Generated by tools/bridge-contract.py from docs/bridge/openapi.json. Do not edit.",
         "package com.example.forgegen", "", "import com.google.gson.JsonElement",
         "import com.google.gson.annotations.SerializedName", ""]
for key, schema in schemas.items():
    lines += ["data class " + name(key) + "("]
    for prop, value in schema.get("properties", {}).items():
        kotlin = re.sub(r"_([a-z])", lambda m: m[1].upper(), prop)
        if kotlin in {"protected", "interface", "object", "when", "is", "in"}:
            kotlin = "`" + kotlin + "`"
        lines += [f'    @SerializedName("{prop}")', f'    val {kotlin}: {kind(value)}? = null,']
    lines += [") {", f'    override fun toString(): String = "{name(key)}(redacted)"', "}", ""]
(root / "app/src/main/java/com/example/forgegen/bridge/BridgeDtos.kt").write_text("\n".join(lines))

routes = []
for path, methods in spec["paths"].items():
    for method, op in methods.items():
        if method not in {"get", "post", "patch", "delete"}:
            continue
        request = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema", {}).get("$ref", "").split("/")[-1]
        response = next((v.get("content", {}).get("application/json", {}).get("schema", {}).get("$ref", "").split("/")[-1]
                         for k, v in op["responses"].items() if k.startswith("2")), "")
        status = int(next(k for k in op["responses"] if k.startswith("2")))
        routes.append({"method": method.upper(), "path": path, "request": request, "response": response, "status": status})
(root / "app/src/test/resources/bridge/routes.json").write_text(json.dumps(routes, indent=2) + "\n")
quoted = lambda value: json.dumps(json.dumps(value, separators=(",", ":"))).replace("$", "\\$")
wire = "// Generated by tools/bridge-contract.py.\npackage com.example.forgegen\n\nimport com.google.gson.JsonParser\n\ninternal object BridgeWireSchemas {\n"
wire += "    val schemas by lazy {\n        JsonParser.parseString(\n            " + quoted(schemas) + ",\n        ).asJsonObject\n    }\n"
wire += "    val routes by lazy {\n        JsonParser.parseString(\n            " + quoted(routes) + ",\n        ).asJsonArray\n    }\n}\n"
(root / "app/src/main/java/com/example/forgegen/bridge/BridgeWireSchemas.kt").write_text(wire)
print(f"Generated {len(schemas)} DTOs and {len(routes)} routes")
